'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,'dist',file),'utf8');
const data=JSON.parse(read('evidence/claim-ledger.json'));
const source=require('../content/assurance-map.json');
const html=read('evidence/claim-ledger.html');
const csv=read('evidence/claim-ledger.csv');
const sitemap=read('sitemap.xml');
const llms=read('llms.txt');
const canonical='https://pinnacle-verify.saripalli.chatgpt.site/evidence/claim-ledger.html';
const expected=new Map([['services',31052382],['registrations',792614],['operational-centres',49],['practitioners',2293],['data-points',2700000000],['patents',16]]);
const gateIds=['homepage-patent-status','homepage-outcome-percentage','homepage-institutional-scale','homepage-language-and-phone-scope','warangal-centre-public-copy-and-postcode','gachibowli-observational-score-change'];
assert.deepEqual(source.claimUseDecisions.map(c=>c.id),gateIds,'Homepage and centre-specific claim-use decisions are recorded in the existing source map');
for(const gate of source.claimUseDecisions){
 assert(gate.claimIds.every(id=>source.claims.some(c=>c.id===id)),gate.id+' references known claims');
 assert(gate.allowedWording&&gate.heldWording.length&&gate.effectiveDate&&gate.sourceAsOf&&gate.reviewerState&&gate.nextReview&&gate.supersededCopy.length&&gate.affectedDestinations.length&&gate.owner,gate.id+' has an actionable review record');
 assert(gate.sourceEvidence.length&&gate.sourceEvidence.every(s=>s.document&&s.version&&/^[0-9a-f]{64}$/.test(s.sha256)&&s.pages&&s.scope),gate.id+' has versioned source pinpoints and hashes');
}
assert.equal(source.claimUseDecisions.find(c=>c.id==='homepage-outcome-percentage').decision,'held');
assert(source.claimUseDecisions.find(c=>c.id==='homepage-patent-status').heldWording.includes('globally patented'));
assert.equal(source.claimUseDecisions.find(c=>c.id==='gachibowli-observational-score-change').decision,'held');
const warangal=source.claimUseDecisions.find(c=>c.id==='warangal-centre-public-copy-and-postcode');
assert.equal(warangal.decision,'held_pending_operations_and_claim_review');
assert(warangal.heldWording.some(s=>s.includes('506001 or 506002')));
assert(warangal.sourceEvidence.some(s=>s.document.includes('All Centers With HFR.xlsx')));
assert.equal(data.canonical,canonical);
assert.equal(data.asOf,'2026-07-17');
assert.equal(data.updated,'2026-09-23');
assert.equal(data.claims.length,expected.size);
assert.deepEqual(new Map(data.claims.map(c=>[c.id,c.value])),expected);
assert.equal(csv.trim().split('\r\n').length,expected.size+1);
assert.equal((html.match(/id="measure-/g)||[]).length,expected.size);
assert(html.includes('31,052,382')&&html.includes('792,614')&&html.includes('2,700,000,000'),'Visible counts match the reports’ comma grouping');
for(const claim of data.claims){
 const original=source.claims.find(c=>c.id===claim.id);
 assert(original&&original.group==='Within the specified report scope',claim.id);
 assert.equal(claim.definition,original.definition,claim.id+' definition');
 assert.equal(claim.summary,original.summary,claim.id+' summary');
 assert.equal(claim.srs4400.sourcePage,original.sourcePages.srs4400,claim.id+' factual pinpoint');
 assert.equal(claim.sae3000.sourcePage,original.sourcePages.sae3000,claim.id+' assurance pinpoint');
 assert(claim.srs4400.sourceUrl.endsWith('/evidence/records/srs4400.html'));
 assert(claim.sae3000.sourceUrl.endsWith('/evidence/records/sae3000.html'));
 assert(html.includes(`id="measure-${claim.id}"`));
 assert(html.includes(claim.srs4400.sourcePage.replaceAll('&','&amp;')));
 assert(csv.includes('"'+claim.id+'"'));
}
const graph=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'];
const dataset=graph.find(node=>node['@type']==='Dataset');
assert.equal(dataset?.variableMeasured?.length,expected.size);
assert.deepEqual(dataset.distribution.map(d=>d.encodingFormat),['application/json','text/csv']);
assert.equal(graph.find(node=>node['@type']==='WebPage')?.mainEntity?.['@id'],canonical+'#dataset');
assert(html.includes('<link rel="canonical" href="'+canonical+'">'));
assert(sitemap.includes('<loc>'+canonical+'</loc>'));
for(const file of ['claim-ledger.html','claim-ledger.json','claim-ledger.csv'])assert(llms.includes('/evidence/'+file));
assert(read('evidence/assurance-map.html').includes('/evidence/claim-ledger.html'));
assert(read('index.html').includes('/evidence/claim-ledger.html'));
for(const forbidden of ['400 billion','97%','ROR request'])assert(!html.includes(forbidden),forbidden);
assert(html.includes('not granted patents')||html.includes('not granted'));
assert(html.includes('no assurance conclusion'));
console.log(JSON.stringify({pass:true,measures:expected.size,cutoff:data.asOf,jsonCsvAndVisibleMatch:true,sourcePinpointsMatch:true,datasetSchema:true,sitemapAndDiscovery:true}));
