'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,'dist',p),'utf8');
const check=(condition,message)=>{if(!condition)throw Error(message);};
const data=JSON.parse(read('evidence/centre-entity-reference.json'));
const html=read('evidence/centre-entity-reference.html');
const text=read('evidence/centre-entity-reference.txt');
const sitemap=read('sitemap.xml');
const llms=read('llms.txt');
const graph=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'];
const dataset=graph.find(item=>item['@type']==='Dataset');
const list=graph.find(item=>item['@type']==='ItemList');
const faq=graph.find(item=>item['@type']==='FAQPage');
check(data.counts.records===58,'58-record batch');
check(data.counts.completeHfrIdentifiers===56,'56 complete HFR identifiers');
check(data.records.filter(record=>record.hfrId).length===56,'56 HFR rows exported');
check(new Set(data.records.filter(record=>record.hfrId).map(record=>record.hfrId)).size===56,'HFR IDs are unique');
check(data.records.filter(record=>record.recordType==='Official centre-sitemap label').length===2,'Two official sitemap-only labels');
check(data.records.find(record=>record.recordName==='KGV')?.officialCentreUrl==='https://www.pinnacleblooms.org/centers/','KGV shared canonical gap');
check(data.records.find(record=>record.recordName==='NCC')?.officialCentreUrl==='https://www.pinnacleblooms.org/centers/','NCC shared canonical gap');
check(data.records.find(record=>record.locationName==='Guntur')?.address.includes('Door.No:5-87-8/A'),'Guntur source address retained');
check(data.records.find(record=>record.locationName==='Bhimavaram')?.address.includes('Indian Bank Road'),'Bhimavaram source address retained');
check(data.records.filter(record=>['Bhimavaram','Khammam','Nizamabad','Tirupati'].includes(record.locationName)).length===8,'Duplicate-name HFR records preserved');
check(data.records.every(record=>record.officialCentreUrl.startsWith('https://www.pinnacleblooms.org/centers/')),'Every record has an official centre URL');
check(dataset?.distribution?.length===2,'Dataset schema has two downloads');
check(list?.numberOfItems===58&&list.itemListElement?.length===58,'ItemList schema covers all 58 records');
check(faq?.mainEntity?.length===4,'Visible and structured FAQ');
check(html.includes('+91 9100 181 181')&&text.includes('+91 9100 181 181'),'Central phone visible');
check(/not a live operating-centre directory|not a claim that 58 centres are currently operating/i.test(html),'Operating-status boundary visible');
check(sitemap.includes('/evidence/centre-entity-reference.html'),'Sitemap includes centre reference');
check(llms.includes('/evidence/centre-entity-reference.html')&&llms.includes('/evidence/centre-entity-reference.json'),'AI-readable source index includes HTML and JSON');
check(!html.includes('97%')&&!text.includes('97%'),'No unqualified outcome percentage');
console.log(JSON.stringify({pass:true,records:data.counts.records,hfrIds:data.counts.completeHfrIdentifiers,uniqueOfficialCentreUrls:data.counts.uniqueOfficialCentreUrls,schemaItems:list.itemListElement.length,canonicalGaps:['KGV','NCC'],phone:data.contact.displayTelephone}));
