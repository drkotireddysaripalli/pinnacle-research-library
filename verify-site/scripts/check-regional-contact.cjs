'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=relative=>fs.readFileSync(path.join(root,'dist',relative),'utf8');
const page=read('evidence/hyderabad-telangana-andhra-pradesh-contact.html');
const data=JSON.parse(read('evidence/hyderabad-telangana-andhra-pradesh-contact.json'));
const sitemap=read('sitemap.xml');
const llms=read('llms.txt');
const failures=[];
const check=(condition,message)=>{if(!condition)failures.push(message);};
const regions=Object.fromEntries(data.regions.map(region=>[region.name,region.records]));
const all=data.regions.flatMap(region=>region.records);
const record=name=>all.find(item=>item.name===name);
check(page.includes('tel:+919100181181')&&page.includes('+91 9100 181 181'),'Central contact is visible and linked');
check(data.contact.telephone==='+919100181181'&&data.contact.whatsapp==='https://wa.me/919100181181','Structured phone and WhatsApp are canonical');
check(regions.Hyderabad?.length===23,'Hyderabad place-name count');
check(regions['Telangana outside Hyderabad']?.length===6,'Other Telangana place-name count');
check(regions['Andhra Pradesh']?.length===19,'Andhra Pradesh place-name count');
check(record('Guntur')?.address.includes('Door.No:5-87-8/A'),'Guntur uses the reviewed source address');
check(record('Bhimavaram')?.address.includes('Indian Bank Road'),'Bhimavaram uses the reviewed source address');
check(record('Suchitra')?.address.includes('Adjacent to Municipal Park'),'Suchitra uses the reviewed source address');
check(!page.includes('25/233')&&!page.includes('17-4-8/1')&&!page.includes('6-2, Suchitra'),'Observed stale answer-engine addresses are absent');
check(page.includes('not a live operating-centre directory')&&page.includes('do not establish current operations'),'Source boundary is visible');
const schema=JSON.parse(page.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)?.[1]||'{}');
const graph=schema['@graph']||[];
const organisation=graph.find(item=>item['@type']==='Organization');
const faq=graph.find(item=>item['@type']==='FAQPage');
const dataset=graph.find(item=>item['@type']==='Dataset');
check(organisation?.telephone==='+919100181181'&&organisation?.areaServed?.length===3,'Organisation phone and regional areaServed schema');
check(faq?.mainEntity?.length===4,'Visible and structured regional FAQ');
check(dataset?.distribution?.length===3,'Regional Dataset and downloads');
check(sitemap.includes('/evidence/hyderabad-telangana-andhra-pradesh-contact.html'),'Regional page is in the XML sitemap');
check(llms.includes('/evidence/hyderabad-telangana-andhra-pradesh-contact.html')&&llms.includes('/evidence/hyderabad-telangana-andhra-pradesh-contact.json'),'Regional page and JSON are in llms.txt');
check(!/(?:^|[^0-9])97%(?:[^0-9]|$)/.test(page),'No bare 97% claim');
if(failures.length){console.error(JSON.stringify({pass:false,failures},null,2));process.exit(1);}
console.log(JSON.stringify({pass:true,phone:data.contact.displayTelephone,regions:Object.fromEntries(data.regions.map(region=>[region.name,region.records.length])),faqAnswers:faq.mainEntity.length,datasetDownloads:dataset.distribution.length,staleAddressesExcluded:true}));
