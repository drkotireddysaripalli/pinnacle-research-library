CREATE TABLE IF NOT EXISTS website_sitemap_pages_v1 (
  url_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  url TEXT NOT NULL,
  host VARCHAR(253) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  module_type VARCHAR(128) NOT NULL,
  decision VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  title TEXT,
  description TEXT,
  keywords_json JSON,
  canonical_url TEXT,
  language VARCHAR(35),
  content_modified_at VARCHAR(40),
  priority_hint DECIMAL(3,2),
  change_frequency_hint VARCHAR(16),
  relevance DECIMAL(6,3),
  og_image TEXT,
  images_json JSON,
  videos_json JSON,
  links_json JSON,
  llm_text MEDIUMTEXT,
  llm_approved BOOLEAN NOT NULL DEFAULT FALSE,
  metadata_json JSON NOT NULL,
  row_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  PRIMARY KEY (url_hash),
  KEY website_sitemap_host_decision (host, decision),
  KEY website_sitemap_module_decision (module_type, decision)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
