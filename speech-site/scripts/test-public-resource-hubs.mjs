import test from 'node:test';
import assert from 'node:assert/strict';
import {publicResourceHubTarget} from '../deployment/public-resource-hubs.mjs';
import {publicLinkTarget} from '../deployment/public-link-target.mjs';
import {canonicalNavigationTarget} from '../deployment/canonical-navigation-aliases.mjs';
import {withManagedSitemaps} from '../deployment/managed-sitemap-runtime.mjs';
for(const map of [publicResourceHubTarget,publicLinkTarget,canonicalNavigationTarget]){
 test(map.name+': exact owned resource links retain query/fragment',()=>{
  for(const name of ['materials','interventions'])for(const prefix of ['','https://www.pinnacleblooms.org','https://pinnacleblooms.org']){
   assert.equal(map(prefix+'/'+name+'/?source=reader&step=2#guide'),'https://'+name+'.pinnacleblooms.org/?source=reader&step=2#guide');
  }
 });
 test(map.name+': no external, private or unqualified destination takeover',()=>{
  for(const value of ['/materials/record','/interventions/private','//example.com/materials','https://example.com/materials','https://www.pinnacleblooms.org.evil/materials','https://user@www.pinnacleblooms.org/materials','https://www.pinnacleblooms.org:8443/materials','/api/enrolment','/verify/','tel:+919100181181',null])assert.equal(map(value),value);
 });
}
test('registered centre sitemap alias serves the exact current generated bytes, GET and HEAD',async()=>{
 let calls=0;const xml='<?xml version="1.0"?><urlset><url><loc>https://www.pinnacleblooms.org/centers</loc></url></urlset>';
 const original={fetch:async()=>{throw Error('Legacy alias fallback is not allowed');}};
 const env={ASSETS:{fetch:async request=>{calls++;assert.equal(new URL(request.url).pathname,'/pinnacle-pages-data/centres-sitemap.xml');return new Response(request.method==='HEAD'?null:xml,{headers:{'content-type':'text/plain'}});}}};
 const worker=withManagedSitemaps(original,{});
 const get=await worker.fetch(new Request('https://www.pinnacleblooms.org/centerssitemap'),env,{});assert.equal(await get.text(),xml);assert.match(get.headers.get('content-type'),/application\/xml/);
 const head=await worker.fetch(new Request('https://www.pinnacleblooms.org/centerssitemap',{method:'HEAD'}),env,{});assert.equal(head.status,200);assert.equal(await head.text(),'');assert.equal(calls,2);
 const absent=await worker.fetch(new Request('https://www.pinnacleblooms.org/centerssitemap'),{ASSETS:{fetch:async()=>new Response(null,{status:404})}},{});assert.equal(absent.status,503);
});
