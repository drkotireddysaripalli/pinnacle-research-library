import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs/promises';

const canonical='https://www.pinnacleblooms.org/best-occupational-therapy-center-india-proven-improvement-rate';
const expected=JSON.parse(await fs.readFile('og-release-20260930/manifest.json','utf8')).assets.find(asset=>asset.id==='occupational');
assert(expected,'OT social card is missing from the reviewed manifest');
const page=await fetch(canonical,{headers:{'cache-control':'no-cache'}});
assert.equal(page.status,200);
const html=await page.text();
const meta=name=>html.match(new RegExp(`<meta (?:property|name)="${name}" content="([^"]+)"`))?.[1];
const imageUrl=meta('og:image');
assert(imageUrl?.includes('?v=20260930-chatgpt'),'The revised social image must have a fresh URL');
assert.equal(meta('twitter:image'),imageUrl);
assert.equal(meta('og:image:secure_url'),imageUrl);
assert.equal(meta('og:image:width'),'1200');
assert.equal(meta('og:image:height'),'630');
const image=await fetch(imageUrl,{headers:{'cache-control':'no-cache'}});
assert.equal(image.status,200);
assert(image.headers.get('content-type')?.startsWith('image/jpeg'));
const bytes=Buffer.from(await image.arrayBuffer());
const sha256=crypto.createHash('sha256').update(bytes).digest('hex');
assert.equal(sha256,expected.sha256,'Public social card must match the reviewed poster');
const report={checkedAt:new Date().toISOString(),canonical,pageStatus:page.status,imageUrl,imageStatus:image.status,imageType:image.headers.get('content-type'),bytes:bytes.length,sha256,expectedSha256:expected.sha256,matchingTwitterImage:true};
await fs.writeFile('deployment/occupational-social-v124-20260930.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
