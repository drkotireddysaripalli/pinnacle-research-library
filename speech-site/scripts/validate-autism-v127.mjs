import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';

const canonical='https://www.pinnacleblooms.org/autism-therapy';
const html=await fs.readFile('dist/autism-therapy.html','utf8');
const sourceMap=JSON.parse(await fs.readFile('dist/pinnacle-pages-data/autism-therapy-evidence.json','utf8'));
const graph=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)?.[1]||'{}')['@graph'];
const service=graph.find(item=>item['@type']==='Service'&&item['@id']===canonical+'#service');
const page=graph.find(item=>item['@type']==='WebPage');
const faq=graph.find(item=>item['@type']==='FAQPage');
const og=html.match(/<meta property="og:image" content="([^"]+)"/)?.[1];
const asset=path.join('dist',new URL(og).pathname.slice(1));
const bytes=await fs.readFile(asset);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]);
const faqHtml=html.match(/<section class="section wrap faq-section"[\s\S]*?<\/section>/)?.[0]||'';

assert(html.includes('<link rel="canonical" href="'+canonical+'">'));
assert(html.includes('index, follow, max-image-preview:large'));
assert(html.includes('Autism therapy is not one fixed programme'));
assert(html.includes('Every autistic child does not need every therapy'));
assert(html.includes('Work toward growing independence and participation'));
assert(html.includes('The right support follows'));
assert(html.includes('62 entries are published Pinnacle network locations'));
assert(html.includes('tel:+919100181181'));
assert(html.includes('data-cta="autism-first-call"'));
assert(html.includes('autism-therapy-evidence.json'));
assert(html.includes('autism-first-conversation-20260930'));
assert(html.includes('autism-selected-path-20260930'));
assert(html.includes('autism-hero-life-first-20260930'));
assert(html.includes('Pinnacle approach, products and evidence'));
assert.equal(service?.areaServed,undefined);
assert.equal(page?.dateModified,'2026-09-30');
assert.equal(faq?.mainEntity?.length,15);
assert.equal((html.match(/<li><div class="path-symbol">/g)||[]).length,7);
assert.equal((faqHtml.match(/<details\b/g)||[]).length,15);
assert.equal(new Set(ids).size,ids.length);
assert.equal(sourceMap.page,canonical);
assert.equal(sourceMap.checkedOn,'2026-09-30');
assert(sourceMap.claims.length>=9&&sourceMap.claims.every(item=>item.source&&item.boundary));
assert(og.includes('autism-social-integrated-20260930')&&og.includes('2026-09-30-autism-life-first'));
assert(bytes.byteLength>100_000&&bytes.byteLength<800_000);
assert.equal(bytes.subarray(0,3).toString('hex'),'ffd8ff');
assert((await fs.readFile('dist/pinnacle-pages-data/speech-sitemap.xml','utf8')).includes('<loc>'+canonical+'</loc><lastmod>2026-09-30</lastmod>'));

const report={checkedAt:new Date().toISOString(),canonical,og,ogBytes:bytes.byteLength,ogSha256:crypto.createHash('sha256').update(bytes).digest('hex'),faqCount:15,stageCount:7,sourceClaims:sourceMap.claims.length,serviceAreaServed:null,pass:true};
await fs.writeFile('deployment/autism-build-v127-20260930.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
